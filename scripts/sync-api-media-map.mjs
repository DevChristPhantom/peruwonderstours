import { access, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const read = async (path) => JSON.parse(await readFile(new URL(path, root), 'utf8'));
const manifest = await read('apps/web/src/lib/content/tour-image-manifest.json');
const original = await read('data/seed/media-manifest.json');
const redirects = await read('data/seed/redirects.json');
const hosts = new Set(['www.andeanperutours.com', 'andeanperutours.com', 'turinet.turismoads.com']);
const keyOf = (value) => {
  const url = new URL(value);
  if (!hosts.has(url.hostname)) return null;
  return `${url.hostname.replace(/^www\./, '')}${url.pathname}`;
};
const map = new Map();
for (const entry of manifest) {
  if (!/^\/tours\/[a-z0-9-]+\.(?:webp|jpe?g|png|avif)$/.test(entry.local)) throw new Error(`Unexpected local media path: ${entry.local}`);
  await access(new URL(`apps/web/public${entry.local}`, root));
  const key = keyOf(entry.source);
  if (key) map.set(key, entry.local);
}
// Only aliases explicitly recorded by the original import manifest are equivalent.
for (const entry of original.items) {
  const urls = [entry.url, ...(entry.variantsSeen ?? [])];
  const known = urls.map((url) => map.get(keyOf(url))).find(Boolean);
  if (known) for (const url of urls) { const key = keyOf(url); if (key) map.set(key, known); }
}
const links = Object.fromEntries(redirects.rules.map((entry) => [new URL(entry.from).pathname, entry.to]));
const sorted = Object.fromEntries([...map.entries()].sort(([a], [b]) => a.localeCompare(b)));
const content = `// Generated by scripts/sync-api-media-map.mjs; source URLs are lookup keys, never network fallbacks.\nexport const LEGACY_MEDIA_MAP: Readonly<Record<string, string>> = ${JSON.stringify(sorted, null, 2)};\nexport const LEGACY_LINK_PATHS: Readonly<Record<string, string>> = ${JSON.stringify(links, null, 2)};\n`;
const target = new URL('apps/api/src/modules/media/domain/legacy-media-map.ts', root);
const adminTarget = new URL('apps/admin/src/lib/legacy-media-map.json', root);
const adminContent = `${JSON.stringify(sorted, null, 2)}\n`;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8').catch(() => '') !== content) throw new Error('API media map is stale. Run node scripts/sync-api-media-map.mjs.');
  if (await readFile(adminTarget, 'utf8').catch(() => '') !== adminContent) throw new Error('Admin media map is stale. Run node scripts/sync-api-media-map.mjs.');
} else { await writeFile(target, content); await writeFile(adminTarget, adminContent); }
console.log(`API media map ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${manifest.length} local images, ${map.size} URL keys (${fileURLToPath(target)}).`);
